<p class="dothelp-intro">
    Nothing here is enforced by the software. It is the set of habits that make the queue work,
    written down so you do not have to infer them.
</p>

<h3>Start of day</h3>

<ol class="dothelp-steps">
    <li>
        <strong>Open <em>Unassigned</em> and sort oldest first.</strong> This is the only check
        that genuinely matters. No automation is chasing these — see
        <a href="{{ route('dothelp.topic', 'escalation') }}">Escalation</a> — so the oldest
        unowned ticket is the desk's real backlog.
    </li>
    <li>
        <strong>Claim what is yours.</strong> If a triage note suggests you, take it. If it
        suggests someone else and they are away, take it anyway and reassign later.
    </li>
    <li>
        <strong>Then work <em>Mine</em>.</strong> Your own list comes after the unowned queue,
        not before it.
    </li>
</ol>

<h3>Working a ticket</h3>

<ul>
    <li>
        <strong>Assign it to yourself before you reply.</strong> An unassigned ticket being
        answered is invisible to everyone else, and two people will duplicate the work.
    </li>
    <li>
        <strong>Set Pending when the ball is with the customer.</strong> It keeps Active
        meaning "needs me".
    </li>
    <li>
        <strong>Use notes for context, replies for customers.</strong> Notes are internal and
        permanent — they are how the next person understands what you already tried.
    </li>
    <li>
        <strong>Close when it is done.</strong> Do not leave it to the sweep. Closing promptly
        keeps the queue honest and the reports meaningful.
    </li>
</ul>

<h3>Habits that pay off later</h3>

<table class="table dothelp-table">
    <thead>
        <tr><th>Habit</th><th>Why</th></tr>
    </thead>
    <tbody>
        <tr>
            <td>Correct bad routing instead of absorbing it</td>
            <td>
                Overrides are measured. Silently doing someone else's tickets teaches the system
                nothing and hides the mismatch.
            </td>
        </tr>
        <tr>
            <td>Reopen wrong closes rather than starting a new ticket</td>
            <td>The history stays in one place and the customer keeps one thread.</td>
        </tr>
        <tr>
            <td>Ask for your triage profile to be updated when your role shifts</td>
            <td>Routing is only as good as the description of what you handle.</td>
        </tr>
        <tr>
            <td>Mark yourself unavailable before leave</td>
            <td>
                Routing skips you, so tickets do not pile up unread in your name while you are
                away.
            </td>
        </tr>
    </tbody>
</table>

<h3>Things you cannot break</h3>

<p>
    Reassigning, reopening, closing, starring, adding notes, changing status — all reversible,
    all visible in the ticket's own history. You do not need permission to correct any of them.
</p>

<p>
    The genuinely destructive operations — permanently deleting old tickets, changing module
    settings — are either switched off, restricted to administrators, or only runnable from the
    server by hand. You will not stumble into one.
</p>
