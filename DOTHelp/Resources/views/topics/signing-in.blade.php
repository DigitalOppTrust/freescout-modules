<p class="dothelp-intro">
    You sign in to the help desk with your <strong>DOT Google account</strong> — the same one
    you use for email. There is no separate help desk password to remember, and none to lose.
</p>

<h3>How to sign in</h3>

<ol>
    <li>Go to <code>support.dotrust.org</code></li>
    <li>Click <strong>Sign in with Google</strong></li>
    <li>Pick your <code>@dotrust.org</code> account</li>
</ol>

<p>
    That is the whole process. If you are already signed in to Google in that browser, it
    usually takes one click.
</p>

<h3>Why there is no password box</h3>

<p>
    Password sign-in is switched off deliberately. Two reasons:
</p>

<ul>
    <li>
        <strong>One fewer password.</strong> A help desk password is one more thing to
        choose badly, reuse, or write down.
    </li>
    <li>
        <strong>Your Google account is already better protected.</strong> It has two-factor
        authentication and DOT's own security rules behind it. Signing in through Google
        means the help desk inherits all of that instead of trying to reproduce it.
    </li>
</ul>

<p>
    It also means that when someone leaves DOT, disabling their Google account closes their
    help desk access at the same moment — rather than depending on someone remembering to do
    it here as well.
</p>

<h3>Who can sign in</h3>

<p>
    Two things must both be true. Your Google account must belong to the
    <strong>dotrust.org</strong> workspace, <em>and</em> you must already have a user account
    on this help desk.
</p>

<p class="dothelp-note">
    Signing in with Google does not create an account. An administrator has to add you first.
    If you have a DOT Google account but have never been added here, the sign-in will be
    refused — that is working as intended, not a fault.
</p>

<h3>If you cannot get in</h3>

<table class="table dothelp-table">
    <thead>
        <tr><th>What you see</th><th>What it usually means</th></tr>
    </thead>
    <tbody>
        <tr>
            <td>"That Google account is not registered on this help desk"</td>
            <td>You do not have an account here yet. Ask an administrator to add you.</td>
        </tr>
        <tr>
            <td>"That account is no longer active"</td>
            <td>Your user here has been disabled. Ask an administrator.</td>
        </tr>
        <tr>
            <td>"Account is not in the dotrust.org workspace"</td>
            <td>You picked a personal Google account. Sign out of it, or use a private window, and pick your DOT one.</td>
        </tr>
        <tr>
            <td>The page just returns to sign-in</td>
            <td>Usually a stale browser tab. Close it, open <code>support.dotrust.org</code> fresh, and try again.</td>
        </tr>
    </tbody>
</table>

<p>
    If none of that helps, tell an administrator. Every sign-in attempt is logged with the
    reason it was refused, so they can see exactly what happened rather than guessing.
</p>

<h3>Signing out</h3>

<p>
    Signing out of the help desk does not sign you out of Google. On a shared or public
    computer, sign out of the Google account as well — otherwise the next person can click
    straight back in.
</p>
