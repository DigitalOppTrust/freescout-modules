<p class="dothelp-intro">
    The mechanics of answering a customer, and the one habit that causes more trouble here than
    anything else: answering them from somewhere other than the ticket.
</p>

<h3>The rule</h3>

<div class="dothelp-callout dothelp-callout-warn">
    <p>
        <strong>Every message to a customer goes out from inside the ticket.</strong>
    </p>
    <p class="dothelp-callout-last">
        Not from your own mailbox. Not as a CC on an internal thread. Not by adding them to an
        email conversation happening elsewhere.
    </p>
</div>

<p>
    Open the conversation, use the reply box, send. The message leaves as
    <strong><code>support@dotrust.org</code></strong>, is attached to the ticket, and the
    customer's response returns to the desk where everyone can see it.
</p>

<h3>Why CCing or replying personally causes real damage</h3>

<p>
    It is not a formality. Each of these is a concrete failure that has a cost:
</p>

<table class="table dothelp-table">
    <thead>
        <tr><th>What breaks</th><th>What actually happens</th></tr>
    </thead>
    <tbody>
        <tr>
            <td><strong>The record</strong></td>
            <td>
                The reply is not on the ticket. The next person to open it sees an unanswered
                customer and either duplicates your work or apologises for a delay that did not
                happen.
            </td>
        </tr>
        <tr>
            <td><strong>The return path</strong></td>
            <td>
                Their answer arrives in your personal inbox instead of the desk. If you are on
                leave or move roles, that thread is gone — nobody else can pick it up.
            </td>
        </tr>
        <tr>
            <td><strong>Your address</strong></td>
            <td>
                The customer now has it and will use it. You have quietly become a private
                support channel with no queue, no cover and no record.
            </td>
        </tr>
        <tr>
            <td><strong>The automation</strong></td>
            <td>
                Closing rules and escalation timers key off recorded replies. A ticket you
                answered by email is treated as never answered — so it is <em>excluded</em> from
                the rule that closes handled tickets, and sits open indefinitely.
            </td>
        </tr>
        <tr>
            <td><strong>The reporting</strong></td>
            <td>
                Response times are measured from real replies sent to the customer. Off-system
                answers make the whole desk look slower than it is, and your own figures worst
                of all.
            </td>
        </tr>
    </tbody>
</table>

<h3>What to use instead</h3>

<table class="table dothelp-table">
    <thead>
        <tr><th>You want to…</th><th>Use</th></tr>
    </thead>
    <tbody>
        <tr>
            <td>Answer the customer</td>
            <td><strong>Reply</strong>, in the ticket. Goes out as the desk address.</td>
        </tr>
        <tr>
            <td>Ask a colleague on the desk something</td>
            <td>
                <strong>Note.</strong> Internal, permanent, attached to the ticket — and
                invisible to the customer. This is what replaces "quick question, CCing you in".
            </td>
        </tr>
        <tr>
            <td>Involve someone outside the desk</td>
            <td>
                <strong>Forward.</strong> Keeps their reply attached to the ticket instead of
                scattering it across inboxes.
            </td>
        </tr>
        <tr>
            <td>Hand the ticket to someone else</td>
            <td><strong>Assign</strong> it to them. They are notified; no email needed.</td>
        </tr>
        <tr>
            <td>Record something you did off-system</td>
            <td>
                <strong>Note.</strong> A phone call, a corridor conversation, an email you sent
                before you knew better — write it down on the ticket.
            </td>
        </tr>
    </tbody>
</table>

<h3>Notes are not replies</h3>

<p>
    Worth stating plainly, because it catches people from both directions. A
    <strong>note is never sent to the customer</strong> — writing an answer as a note means the
    customer never receives it. A <strong>reply always is</strong> — venting or speculating in
    the reply box sends it.
</p>

<p>
    The interface distinguishes them clearly, but check which one you are in before typing
    anything you would not want the customer to read.
</p>

<h3>Practical habits</h3>

<ul>
    <li>
        <strong>Assign the ticket to yourself before replying.</strong> An unassigned ticket
        being answered is invisible to everyone else.
    </li>
    <li>
        <strong>Set Pending after you reply</strong> when you are waiting on the customer. It
        keeps <em>Active</em> meaning "needs me".
    </li>
    <li>
        <strong>Do not start a new ticket for a continuing issue.</strong> Reopen the original
        so the history stays in one place — the customer keeps one thread, and so do you.
    </li>
    <li>
        <strong>Write the note before you forget.</strong> Context you carry in your head is
        lost the moment the ticket changes hands.
    </li>
</ul>

<h3>If you have already replied from your own inbox</h3>

<div class="dothelp-callout">
    <p>
        Not a disaster, and worth fixing rather than hiding:
    </p>
    <ol class="dothelp-steps">
        <li>Paste what you sent into the ticket as a <strong>note</strong>, so the record is complete.</li>
        <li>Carry on inside the ticket from that point.</li>
        <li>
            If the customer replies to you personally, paste their message in as a note too, then
            answer through the ticket — that pulls the conversation back where it belongs.
        </li>
    </ol>
    <p class="dothelp-callout-last">
        Nobody minds this happening once. The problem is only when it becomes how you work.
    </p>
</div>
